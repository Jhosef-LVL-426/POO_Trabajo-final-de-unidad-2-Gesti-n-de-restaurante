CREATE TABLE IF NOT EXISTS platos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(90) NOT NULL, categoria VARCHAR(40) NOT NULL,
 precio DECIMAL(10,2) NOT NULL, disponible BOOLEAN DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS mesas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 numero INT NOT NULL UNIQUE, capacidad INT NOT NULL, estado VARCHAR(20) DEFAULT 'LIBRE'
);
CREATE TABLE IF NOT EXISTS clientes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL, telefono VARCHAR(20)
);
CREATE TABLE IF NOT EXISTS pedidos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP, mesa_id BIGINT,
 cliente VARCHAR(100), total DECIMAL(10,2) NOT NULL, estado VARCHAR(20) DEFAULT 'PENDIENTE'
);
CREATE TABLE IF NOT EXISTS detalle_pedido (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pedido_id BIGINT NOT NULL,
 plato_id BIGINT NOT NULL, plato VARCHAR(90) NOT NULL, cantidad INT NOT NULL,
 precio DECIMAL(10,2) NOT NULL, subtotal DECIMAL(10,2) NOT NULL
);
CREATE TABLE IF NOT EXISTS reservas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cliente VARCHAR(100) NOT NULL,
 telefono VARCHAR(20), fecha DATE NOT NULL, hora VARCHAR(10) NOT NULL,
 personas INT NOT NULL, estado VARCHAR(20) DEFAULT 'CONFIRMADA'
);
CREATE TABLE IF NOT EXISTS insumos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre VARCHAR(90) NOT NULL,
 unidad VARCHAR(20) NOT NULL, stock DECIMAL(10,2) NOT NULL, minimo DECIMAL(10,2) NOT NULL
);
